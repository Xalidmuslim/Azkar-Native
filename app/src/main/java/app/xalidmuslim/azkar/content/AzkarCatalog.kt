    private val itemsById: Map<String, AzkarContentItem> = all.associateBy { it.id }

    val stableIds: Set<String> = itemsById.keys

    fun item(id: String): AzkarContentItem =
        requireNotNull(itemsById[id]) { "Unknown dhikr id: $id" }

    fun itemsFor(period: AzkarPeriod): List<AzkarContentItem> =
        all.filter { period in it.periods }

    fun readingItemsFor(period: AzkarPeriod): List<AzkarReadingItem> =
        itemsFor(period).map { it.resolve(period) }

    fun firstReadingItem(period: AzkarPeriod): AzkarReadingItem =
        readingItemsFor(period).first()

    private fun bothPeriods(): Set<AzkarPeriod> =
        setOf(AzkarPeriod.Morning, AzkarPeriod.Evening)
